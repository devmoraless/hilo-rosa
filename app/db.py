"""Tables (SQLModel). These ARE the contract for storage; app/schemas holds the API shapes.

Every row is fictitious demo data. Dates are ISO strings (YYYY-MM-DD or full ISO timestamps)
so SQLite, JSON and the IndexedDB snapshot all agree without conversions.
"""

from datetime import UTC, datetime
from uuid import uuid4

from sqlmodel import Field, SQLModel


def new_id() -> str:
    return uuid4().hex


def now_iso() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


class Patient(SQLModel, table=True):
    id: str = Field(default_factory=new_id, primary_key=True)
    folio: str = Field(index=True, unique=True)  # EIRA-XXXX, printed on the credential
    nombre: str
    apellidos: str
    fecha_nacimiento: str  # YYYY-MM-DD
    municipio: str = Field(index=True)
    telefono: str | None = None
    telefono_propio: bool = True
    canal_aviso: str = "telegram"  # telegram | sms | en_persona
    qr_token: str = Field(index=True, unique=True)  # opaque, revocable, carries no personal data
    qr_revocado: bool = False
    version: int = 1
    demo_data: bool = True


class TrustedContact(SQLModel, table=True):
    id: str = Field(default_factory=new_id, primary_key=True)
    patient_id: str = Field(index=True, foreign_key="patient.id")
    nombre: str
    parentesco: str
    telefono: str
    consentimiento_at: str = Field(default_factory=now_iso)
    activo: bool = True


class Jornada(SQLModel, table=True):
    id: str = Field(primary_key=True)
    municipio: str
    sede: str
    fecha: str


class Visit(SQLModel, table=True):
    id: str = Field(default_factory=new_id, primary_key=True)
    patient_id: str = Field(index=True, foreign_key="patient.id")
    jornada_id: str | None = Field(default=None, foreign_key="jornada.id")
    device_id: str = "seed"
    created_at: str = Field(default_factory=now_iso)


class Study(SQLModel, table=True):
    id: str = Field(default_factory=new_id, primary_key=True)
    visit_id: str | None = Field(default=None, foreign_key="visit.id")
    patient_id: str = Field(index=True, foreign_key="patient.id")
    tipo: str  # papanicolaou | ultrasonido | mastografia | nutricion
    folio_muestra: str | None = None
    fecha: str


class Result(SQLModel, table=True):
    id: str = Field(default_factory=new_id, primary_key=True)
    study_id: str | None = Field(default=None, foreign_key="study.id")
    patient_id: str | None = Field(default=None, index=True, foreign_key="patient.id")
    pdf_path: str
    pdf_nombre: str = ""
    folio_detectado: str | None = None
    sugerencia_patient_id: str | None = None
    estado: str = "pendiente_asociar"  # see app.schemas.RESULT_STATES
    tipo_estudio: str = "papanicolaou"
    bethesda: str | None = None
    birads: int | None = None
    conducta: str | None = None
    notas: str | None = None
    clasificacion: str | None = None  # normal | seguimiento | repetir (derived by rules)
    prioridad: str | None = None  # normal | alta
    proximo_control: str | None = None
    explicacion_clara: str | None = None
    autorizado_por_nombre: str | None = None
    autorizado_por_cedula: str | None = None
    autorizado_at: str | None = None
    notificado_at: str | None = None
    visto_at: str | None = None
    visto_por: str | None = None
    created_at: str = Field(default_factory=now_iso)


class FollowUpTask(SQLModel, table=True):
    id: str = Field(default_factory=new_id, primary_key=True)
    patient_id: str = Field(index=True, foreign_key="patient.id")
    result_id: str | None = Field(default=None, foreign_key="result.id")
    tipo: str  # llamar | referencia_2o_nivel | citar_nueva_muestra | recordatorio
    estado: str = "abierta"  # abierta | hecha
    fecha_objetivo: str | None = None
    created_at: str = Field(default_factory=now_iso)


class AuditLog(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    actor: str
    rol: str
    accion: str
    entidad_id: str
    ts: str = Field(default_factory=now_iso)
    prev_hash: str
    hash: str


class SyncOp(SQLModel, table=True):
    op_id: str = Field(primary_key=True)  # idempotency key generated by the device
    device_id: str
    tipo: str
    payload: str  # JSON
    base_version: int | None = None
    status: str = "applied"  # applied | conflict
    applied_at: str = Field(default_factory=now_iso)
